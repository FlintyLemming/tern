import { expect, test, type Page } from '@playwright/test'
import { appendFileSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

// Spec §16 item 1: from `docker compose up` to tasks that ran, without
// entering a container. The only thing done outside the browser is what the
// remote end's administrator does: adding the public key to the SSH
// server's authorized_keys (through the directory bound to its /keys).
// Results are checked in the host directories bound into the containers.

const url = () => process.env.TERN_E2E_URL!
const dir = (...p: string[]) => join(process.env.TERN_E2E_DIR!, ...p)
const ADMIN = 'e2e admin password 1'

test.describe.configure({ mode: 'serial' })

// files lists a directory tree on the host: relative path → content.
function files(root: string): Record<string, string> {
  const out: Record<string, string> = {}
  const walk = (d: string) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name)
      if (statSync(p).isDirectory()) walk(p)
      else out[relative(root, p)] = readFileSync(p, 'utf8')
    }
  }
  walk(root)
  return out
}

// choose picks an option of one of the interface's select boxes.
async function choose(page: Page, label: string, option: string | RegExp) {
  await page.getByRole('combobox', { name: label, exact: true }).click()
  await page.getByRole('option', { name: option }).click()
}

// runFromTasks starts a run from the task list (kind: the row's button) and
// opens its detail page through the toast's link.
async function runFromTasks(page: Page, task: string, button: '立即运行' | '试运行') {
  await page.getByRole('link', { name: '任务', exact: true }).click()
  const row = page.getByRole('row').filter({ has: page.getByRole('link', { name: task, exact: true }) })
  // Earlier toasts may still be up: follow the link of the new one.
  const toastLinks = page.getByRole('link', { name: '查看运行' })
  const before = new Set(await toastLinks.evaluateAll((as) => as.map((a) => a.getAttribute('href'))))
  await row.getByRole('button', { name: button }).click()
  await expect.poll(async () => (await toastLinks.evaluateAll((as) => as.map((a) => a.getAttribute('href')))).filter((h) => !before.has(h)).length).toBe(1)
  const href = (await toastLinks.evaluateAll((as) => as.map((a) => a.getAttribute('href')))).find((h) => !before.has(h))!
  await page.locator(`a[href="${href}"]`).click()
  // The detail page's title is "<task> · <kind of run>".
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(`${task} · ${button === '试运行' ? '试运行' : kind(task)}`)
}

const kind = (task: string) => (task.includes('backup') ? '备份' : '同步')

async function waitFinished(page: Page, status = '成功') {
  // The detail page follows the run live; the status settles at the end.
  await expect(page.locator('dd').filter({ hasText: /^(成功|完成但有警告|部分失败|失败|已取消|已跳过|被中断)$/ }).first()).toHaveText(status, {
    timeout: 5 * 60 * 1000,
  })
}

async function login(page: Page) {
  await page.goto(url())
  await page.getByLabel('管理员密码').fill(ADMIN)
  await page.getByRole('button', { name: '登录' }).click()
  await expect(page.getByRole('heading', { name: '概览' })).toBeVisible()
}

test('first run: from wizard to a successful sync, backup and restore', async ({ page }) => {
  // 1. The wizard: one password and a node name.
  await page.goto(url())
  await expect(page).toHaveURL(/\/setup$/)
  await page.getByLabel('管理员密码').fill(ADMIN)
  await page.getByLabel('再输一遍').fill(ADMIN)
  await page.getByLabel('节点名').fill('nas-e2e')
  await page.getByRole('button', { name: '完成初始化' }).click()
  await expect(page.getByRole('heading', { name: '概览' })).toBeVisible()

  // 2. A key generated by tern; its public half goes to the remote end.
  await page.getByRole('link', { name: '连接与密钥' }).click()
  await page.getByRole('tab', { name: '密钥' }).click()
  await page.getByRole('button', { name: '生成密钥' }).click()
  const gen = page.getByRole('dialog')
  await gen.getByLabel('名称').fill('e2e-key')
  await gen.getByRole('button', { name: '生成', exact: true }).click()
  const pub = (await gen.locator('pre, code').filter({ hasText: /^ssh-ed25519 / }).first().textContent())!.trim()
  expect(pub).toMatch(/^ssh-ed25519 [A-Za-z0-9+/=]+/)
  appendFileSync(dir('keys', 'authorized_keys'), pub + '\n')
  await gen.getByRole('button', { name: '完成' }).click()

  // 3. The SSH connection, its fingerprint checked against the real one.
  await page.getByRole('tab', { name: '连接' }).click()
  await page.getByRole('button', { name: '新建 SSH 连接' }).click()
  const conn = page.getByRole('dialog')
  await conn.getByLabel('名称').fill('nas-b')
  await conn.getByLabel('主机').fill('sshd')
  await conn.getByLabel('用户名').fill('backup')
  await choose(page, '密钥', 'e2e-key')
  await conn.getByRole('button', { name: '获取指纹' }).click()
  await expect(conn.locator('dd.font-mono').filter({ hasText: /^SHA256:/ })).toHaveText(process.env.TERN_E2E_HOSTKEY_FP!)
  await expect(conn.getByRole('button', { name: '保存' })).toBeDisabled()
  await conn.getByText('我已在对端核对过这个指纹').click()
  await conn.getByRole('button', { name: '保存' }).click()
  const connRow = page.getByRole('row').filter({ hasText: 'nas-b' })
  await connRow.getByRole('button', { name: '测试连接' }).click()
  await expect(page.getByText('连接正常', { exact: true })).toBeVisible()

  // 4. A manual rsync push of one folder pair; a dry run first.
  await page.getByRole('link', { name: '任务', exact: true }).click()
  await page.getByRole('button', { name: '新建任务' }).click()
  await page.getByRole('dialog').getByRole('button', { name: /^同步/ }).click()
  await page.getByLabel('名称', { exact: true }).fill('e2e-sync')
  await choose(page, '协议', 'rsync over SSH')
  await choose(page, '连接', 'nas-b')
  await page.getByLabel('本机路径').fill('/sources/e2e')
  await page.getByLabel('远端路径').fill('/srv/e2e-dst')
  await page.getByRole('button', { name: '保存' }).click()
  await expect(page.getByRole('link', { name: 'e2e-sync', exact: true })).toBeVisible()
  await runFromTasks(page, 'e2e-sync', '试运行')
  await waitFinished(page)
  await expect(page.getByText(/plan: \d+ to transfer/)).toBeVisible()

  // 5. The real run: the remote end gets exactly the source.
  await runFromTasks(page, 'e2e-sync', '立即运行')
  await waitFinished(page)
  expect(files(dir('remote', 'e2e-dst'))).toEqual(files(dir('sources', 'e2e')))

  // 6. A backup task: nothing is created before the recovery information
  //    has been kept.
  await page.getByRole('link', { name: '任务', exact: true }).click()
  await page.getByRole('button', { name: '新建任务' }).click()
  await page.getByRole('dialog').getByRole('button', { name: /^备份/ }).click()
  await page.getByLabel('名称', { exact: true }).fill('e2e-backup')
  await page.getByLabel('源目录').fill('/sources/e2e')
  await choose(page, '仓库连接', 'nas-b')
  await page.getByLabel('远端路径').fill('/srv/e2e-repo')
  await expect(page.getByLabel('仓库密码', { exact: true })).not.toHaveValue('')
  await page.getByRole('button', { name: '保存' }).click()
  const rec = page.getByRole('dialog', { name: '恢复信息' })
  const create = rec.getByRole('button', { name: '确认并创建' })
  await expect(create).toBeDisabled()
  const download = page.waitForEvent('download')
  await rec.getByRole('button', { name: '下载恢复信息' }).click()
  const info = readFileSync((await (await download).path())!, 'utf8')
  expect(info).toContain('/srv/e2e-repo')
  await rec.getByText('我已把恢复信息保存到这台机器以外的地方').click()
  await create.click()
  await expect(page.getByText('已初始化新仓库', { exact: true })).toBeVisible()

  // 7. The backup runs and leaves one snapshot.
  await runFromTasks(page, 'e2e-backup', '立即运行')
  await waitFinished(page)
  await page.getByRole('link', { name: '快照与恢复' }).click()
  await choose(page, '备份任务', 'e2e-backup')
  const snapRows = page.getByRole('row').filter({ has: page.getByRole('button', { name: '恢复' }) })
  await expect(snapRows).toHaveCount(1)

  // 8. Restore it into a new directory under /targets.
  await snapRows.getByRole('button', { name: '恢复' }).click()
  await page.getByRole('dialog').getByLabel('目标目录').fill('/targets/restore-e2e')
  // A new backup task's first success is followed by its automatic prune
  // and check; while they run the restore is refused ("已在排队或运行").
  // Do what a person would: try again a little later.
  await expect(async () => {
    await page.getByRole('dialog').getByRole('button', { name: '开始恢复' }).click()
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('e2e-backup · 恢复', { timeout: 5000 })
  }).toPass({ timeout: 5 * 60 * 1000, intervals: [5000] })
  await waitFinished(page)
  expect(files(dir('targets', 'restore-e2e', 'sources', 'e2e'))).toEqual(files(dir('sources', 'e2e')))

  // 9. The overview: both tasks succeeded, nothing is flagged.
  await page.getByRole('link', { name: '概览' }).click()
  for (const name of ['e2e-sync', 'e2e-backup']) {
    await expect(page.getByRole('row').filter({ hasText: name }).getByText('成功')).toBeVisible()
  }
  await expect(page.getByText(/个任务超过预期时间没有成功/)).toHaveCount(0)
})

